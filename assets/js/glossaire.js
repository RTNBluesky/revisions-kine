(function () {
  'use strict';

  var G = window.GLOSSAIRE;
  var bulle = null, actif = null, minuterie = null;

  function creerBulle() {
    if (bulle) return bulle;
    bulle = document.createElement('div');
    bulle.id = 'glo-bulle';
    bulle.setAttribute('role', 'tooltip');
    document.body.appendChild(bulle);
    return bulle;
  }

  function placer(cible) {
    var e = G[cible.dataset.terme];
    if (!e) return;
    var b = creerBulle();
    b.innerHTML = '<span class="glo-terme"></span><span class="glo-def"></span>';
    b.querySelector('.glo-terme').textContent = e.t;
    b.querySelector('.glo-def').textContent = e.d;
    b.className = '';

    var r = cible.getBoundingClientRect();
    var sx = window.pageXOffset, sy = window.pageYOffset;
    b.style.left = '0px'; b.style.top = '0px';           /* mesurer sans contrainte */
    var lb = b.getBoundingClientRect();

    var marge = 12;
    var gauche = r.left + sx + r.width / 2 - lb.width / 2;
    gauche = Math.max(marge + sx, Math.min(gauche, sx + document.documentElement.clientWidth - lb.width - marge));

    var dessous = r.bottom + lb.height + 14 < window.innerHeight || r.top < lb.height + 14;
    var haut = dessous ? r.bottom + sy + 9 : r.top + sy - lb.height - 9;

    b.classList.add(dessous ? 'dessous' : 'dessus');
    b.style.left = Math.round(gauche) + 'px';
    b.style.top = Math.round(haut) + 'px';
    /* la flèche pointe le mot, même si la bulle a été recadrée */
    var fleche = r.left + sx + r.width / 2 - gauche - 4;
    b.style.setProperty('--fleche', Math.max(12, Math.min(fleche, lb.width - 22)) + 'px');

    requestAnimationFrame(function () { b.classList.add('visible'); });
    cible.setAttribute('aria-expanded', 'true');
    actif = cible;
  }

  function cacher() {
    clearTimeout(minuterie);
    if (bulle) bulle.classList.remove('visible');
    if (actif) { actif.setAttribute('aria-expanded', 'false'); actif = null; }
  }

  function montrer(cible) {
    if (actif === cible) return;
    cacher();
    placer(cible);
  }

  document.addEventListener('mouseover', function (ev) {
    var c = ev.target.closest && ev.target.closest('.def');
    if (c) { clearTimeout(minuterie); minuterie = setTimeout(function () { montrer(c); }, 90); }
  });
  document.addEventListener('mouseout', function (ev) {
    var c = ev.target.closest && ev.target.closest('.def');
    if (c) { clearTimeout(minuterie); minuterie = setTimeout(cacher, 140); }
  });
  document.addEventListener('focusin', function (ev) {
    var c = ev.target.closest && ev.target.closest('.def');
    if (c) montrer(c);
  });
  document.addEventListener('focusout', cacher);

  /* au toucher : un tap ouvre, un tap ailleurs ferme */
  document.addEventListener('click', function (ev) {
    var c = ev.target.closest && ev.target.closest('.def');
    if (c) { ev.preventDefault(); (actif === c) ? cacher() : montrer(c); }
    else if (actif) cacher();
  });
  document.addEventListener('keydown', function (ev) { if (ev.key === 'Escape') cacher(); });
  window.addEventListener('scroll', cacher, { passive: true });
  window.addEventListener('resize', cacher);

  /* rendre chaque terme atteignable au clavier et lisible par un lecteur d'écran */
  function preparer() {
    document.querySelectorAll('.def[data-terme]').forEach(function (el) {
      var e = G[el.dataset.terme];
      if (!e) { el.classList.remove('def'); return; }   /* clé inconnue : on n'affiche rien */
      el.setAttribute('tabindex', '0');
      el.setAttribute('role', 'button');
      el.setAttribute('aria-expanded', 'false');
      el.setAttribute('title', e.t + ' — ' + e.d);      /* repli si le script est bloqué */
      el.setAttribute('data-impression', e.t);
    });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', preparer);
  else preparer();
})();
